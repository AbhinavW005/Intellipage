from contextlib import contextmanager
from pathlib import Path

import pytest

from intellipage.dqn import ACTION_NAMES
from intellipage import oracle_database
from intellipage.oracle_database import (
    _pdb_from_dsn,
    _quote_oracle_password,
    normalize_oracle_admin_user,
)


def test_oracle_schema_is_native_and_complete():
    schema = (
        Path(__file__).resolve().parents[1] / "database" / "oracle_schema.sql"
    ).read_text(encoding="utf-8").upper()
    assert "GENERATED BY DEFAULT ON NULL AS IDENTITY" in schema
    assert "IS JSON" in schema
    assert "CREATE OR REPLACE VIEW POLICY_PERFORMANCE" in schema
    assert "WHERE RECENCY_RANK = 1" in schema
    assert "S.READ_BYTES" in schema
    assert "AVG(REWARD) AS AVG_REWARD" in schema
    assert "AVG_LATENCY_IMPROVEMENT_MS" in schema
    assert "AUTO_INCREMENT" not in schema
    assert "ENGINE=INNODB" not in schema


def test_oracle_password_quoting_and_dqn_action_name():
    assert _quote_oracle_password('safe"password') == 'safe""password'
    with pytest.raises(ValueError):
        _quote_oracle_password("")
    assert ACTION_NAMES[3] == "database_warm"


def test_pdb_name_is_derived_safely_from_easy_connect_dsn():
    assert _pdb_from_dsn("127.0.0.1:1521/XEPDB1") == "XEPDB1"
    with pytest.raises(ValueError):
        _pdb_from_dsn("127.0.0.1:1521")


def test_sqlplus_style_sysdba_username_is_normalized():
    assert normalize_oracle_admin_user("  sys   as   sysdba  ") == ("sys", True)
    assert normalize_oracle_admin_user("SYSTEM") == ("SYSTEM", False)
    with pytest.raises(ValueError):
        normalize_oracle_admin_user("AS SYSDBA")


def test_bootstrap_grants_sequence_creation_before_identity_tables(monkeypatch, tmp_path):
    executed: list[str] = []

    class FakeOracleError(Exception):
        pass

    class Cursor:
        def execute(self, statement, _parameters=None):
            executed.append(statement)
            if statement.startswith("CREATE TABLE") and not any(
                "CREATE SEQUENCE" in grant for grant in executed if grant.startswith("GRANT ")
            ):
                raise FakeOracleError("ORA-01031: insufficient privileges")

        def fetchone(self):
            return (0,)

        def close(self):
            pass

    class Connection:
        def cursor(self):
            return Cursor()

        def commit(self):
            pass

        def rollback(self):
            pass

        def close(self):
            pass

    class Driver:
        Error = FakeOracleError
        DatabaseError = FakeOracleError
        AUTH_MODE_SYSDBA = 1
        AUTH_MODE_DEFAULT = 0

        @staticmethod
        def connect(**_kwargs):
            return Connection()

    @contextmanager
    def runtime_connection(_repository):
        yield Connection()

    monkeypatch.setattr(oracle_database, "_driver_module", lambda _config=None: Driver)
    monkeypatch.setattr(oracle_database.OracleRepository, "connection", runtime_connection)
    schema_path = tmp_path / "oracle_schema.sql"
    schema_path.write_text(
        "CREATE TABLE processes (process_id NUMBER GENERATED AS IDENTITY PRIMARY KEY);",
        encoding="utf-8",
    )

    oracle_database.bootstrap_oracle_database(
        dsn="127.0.0.1:1521/XEPDB1",
        admin_user="SYS AS SYSDBA",
        admin_password="test-admin-password",
        app_user="intellipage_app",
        app_password="test-app-password",
        schema_path=schema_path,
    )

    assert any("CREATE SEQUENCE" in sql for sql in executed if sql.startswith("GRANT "))
