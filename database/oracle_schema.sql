CREATE TABLE processes (
    process_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    windows_pid NUMBER(10) NOT NULL,
    process_name VARCHAR2(260 CHAR) NOT NULL,
    process_started_at TIMESTAMP(6) NOT NULL,
    first_seen TIMESTAMP(6) NOT NULL,
    last_seen TIMESTAMP(6) NOT NULL,
    CONSTRAINT uq_process_instance UNIQUE (windows_pid, process_started_at)
);

CREATE TABLE system_samples (
    sample_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    sampled_at TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    memory_total_bytes NUMBER(20) NOT NULL,
    memory_available_bytes NUMBER(20) NOT NULL,
    memory_percent NUMBER(8,3) NOT NULL,
    swap_used_bytes NUMBER(20) NOT NULL,
    swap_percent NUMBER(8,3) NOT NULL,
    process_count NUMBER(10) NOT NULL
);

CREATE TABLE process_samples (
    sample_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    process_id NUMBER NOT NULL,
    sampled_at TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    page_faults NUMBER(20) NOT NULL,
    working_set_bytes NUMBER(20) NOT NULL,
    private_bytes NUMBER(20) NOT NULL,
    cpu_percent NUMBER(9,3) NOT NULL,
    read_bytes NUMBER(20) NOT NULL,
    write_bytes NUMBER(20) NOT NULL,
    CONSTRAINT fk_process_sample_process FOREIGN KEY (process_id)
        REFERENCES processes(process_id) ON DELETE CASCADE
);

CREATE TABLE optimization_actions (
    action_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    action_kind VARCHAR2(40 CHAR) NOT NULL,
    target VARCHAR2(1000 CHAR) NOT NULL,
    started_at TIMESTAMP(6) NOT NULL,
    duration_ms NUMBER(18,6) NOT NULL,
    success NUMBER(1) NOT NULL,
    bytes_touched NUMBER(20) DEFAULT 0 NOT NULL,
    message VARCHAR2(2000 CHAR),
    metadata_json CLOB,
    CONSTRAINT ck_action_success CHECK (success IN (0, 1)),
    CONSTRAINT ck_action_metadata_json CHECK (metadata_json IS JSON)
);

CREATE TABLE experiments (
    experiment_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    experiment_type VARCHAR2(80 CHAR) NOT NULL,
    target VARCHAR2(1000 CHAR) NOT NULL,
    policy_name VARCHAR2(80 CHAR) NOT NULL,
    action_id NUMBER NOT NULL,
    baseline_latency_ms NUMBER(18,6) NOT NULL,
    post_action_latency_ms NUMBER(18,6) NOT NULL,
    page_faults_before NUMBER(20) NOT NULL,
    page_faults_after NUMBER(20) NOT NULL,
    working_set_before NUMBER(20) NOT NULL,
    working_set_after NUMBER(20) NOT NULL,
    reward NUMBER(18,9) NOT NULL,
    created_at TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_experiment_action FOREIGN KEY (action_id)
        REFERENCES optimization_actions(action_id)
);

CREATE TABLE dqn_experiences (
    experience_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    state_json CLOB NOT NULL,
    action_index NUMBER(3) NOT NULL,
    reward NUMBER(18,9) NOT NULL,
    next_state_json CLOB NOT NULL,
    done NUMBER(1) NOT NULL,
    created_at TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT ck_dqn_done CHECK (done IN (0, 1)),
    CONSTRAINT ck_dqn_state_json CHECK (state_json IS JSON),
    CONSTRAINT ck_dqn_next_state_json CHECK (next_state_json IS JSON)
);

CREATE TABLE query_metrics (
    metric_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    query_digest CHAR(64 CHAR) NOT NULL,
    statement_name VARCHAR2(160 CHAR) NOT NULL,
    duration_ms NUMBER(18,6) NOT NULL,
    rows_returned NUMBER(20) NOT NULL,
    explain_text CLOB,
    measured_at TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX ix_process_samples_time ON process_samples(sampled_at);
CREATE INDEX ix_process_samples_process_time ON process_samples(process_id, sampled_at);
CREATE INDEX ix_system_samples_time ON system_samples(sampled_at);
CREATE INDEX ix_experiments_policy ON experiments(policy_name, created_at);
CREATE INDEX ix_query_metrics_digest ON query_metrics(query_digest, measured_at);

CREATE OR REPLACE VIEW policy_performance AS
SELECT policy_name,
       COUNT(*) AS experiment_count,
       AVG(baseline_latency_ms) AS avg_baseline_latency_ms,
       AVG(post_action_latency_ms) AS avg_post_action_latency_ms,
       AVG(baseline_latency_ms - post_action_latency_ms) AS avg_latency_improvement_ms,
       AVG(reward) AS avg_reward,
       SUM(page_faults_after - page_faults_before) AS observed_page_fault_delta
FROM experiments
GROUP BY policy_name;

CREATE OR REPLACE VIEW latest_process_metrics AS
SELECT process_id,
       windows_pid,
       process_name,
       sampled_at,
       page_faults,
       working_set_bytes,
       private_bytes,
       cpu_percent,
       read_bytes,
       write_bytes
FROM (
    SELECT p.process_id,
           p.windows_pid,
           p.process_name,
           s.sampled_at,
           s.page_faults,
           s.working_set_bytes,
           s.private_bytes,
           s.cpu_percent,
           s.read_bytes,
           s.write_bytes,
           ROW_NUMBER() OVER (
               PARTITION BY p.process_id ORDER BY s.sampled_at DESC, s.sample_id DESC
           ) AS recency_rank
    FROM processes p
    JOIN process_samples s ON s.process_id = p.process_id
)
WHERE recency_rank = 1;
